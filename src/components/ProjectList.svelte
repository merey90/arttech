Human–Machine Sonic Interfaces
Development of sensitive musical interfaces based on biofeedback, neurophysiological data, and empathic algorithms. The aim is to design instruments capable of engaging in real-time dialogue with performers, responding to emotion, movement, and breath.

Sonic Futures and Algorithmic Aesthetics
